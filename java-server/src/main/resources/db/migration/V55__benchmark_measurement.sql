-- V55: benchmark measurement (spec 2026-10-13-benchmark-measurement-design).
--
-- screen_candidate          every pre-screen candidate a capture hunter (echo, lazarus, merger,
--                           insider, spin, index) handed its LLM — picked AND rejected. Written by
--                           ScreenCandidateRecorder: live from HuntController.handleFetch (source
--                           LIVE) or by the one-time import endpoint (source BACKFILL). One row per
--                           (agent, UTC day, symbol); a second fetch the same day is a duplicate.
--                           No currency column (no item carries one; CurrencyResolver uses the
--                           symbol suffix) and no run_id (not available in handleFetch).
-- benchmark_outcome         one row per (kind, agent, symbol, entry_ref_date, horizon), written
--                           once complete by BenchmarkOutcomeJob and never recomputed.
--                           event_start_date is the event's identity (first appearance for
--                           CANDIDATE, prey date for SIGNAL); entry_ref_at is the exact reference
--                           timestamp T. All returns are fractions in EUR; excess is null only for
--                           NO_ENTRY rows.
-- benchmark_symbol_no_data  per-symbol count of nights on which Agora served no bars at all;
--                           the job gives a symbol up after 3 nights and deletes the row as soon as
--                           bars appear.
-- Like the executor tables, none of these carries a user_id: one research pipeline, not per-user data.

CREATE TABLE screen_candidate (
    id          UUID          PRIMARY KEY,
    agent       TEXT          NOT NULL,
    fetched_at  TIMESTAMPTZ   NOT NULL,
    as_of_date  DATE          NOT NULL,
    symbol      TEXT          NOT NULL,
    score       NUMERIC,
    extra       JSONB,
    source      TEXT          NOT NULL,
    created_at  TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT screen_candidate_source_ck CHECK (source IN ('LIVE', 'BACKFILL')),
    CONSTRAINT screen_candidate_uk UNIQUE (agent, as_of_date, symbol)
);

CREATE TABLE benchmark_outcome (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind                  TEXT          NOT NULL,
    agent                 TEXT          NOT NULL,
    symbol                TEXT          NOT NULL,
    event_start_date      DATE          NOT NULL,
    entry_ref_date        DATE          NOT NULL,
    entry_ref_at          TIMESTAMPTZ   NOT NULL,
    picked                BOOLEAN,
    horizon_days          INT           NOT NULL,
    entry_date            DATE,
    entry_price           NUMERIC(18,6),
    exit_date             DATE,
    exit_price            NUMERIC(18,6),
    currency              TEXT,
    fx_entry              NUMERIC(18,8),
    fx_exit               NUMERIC(18,8),
    return_eur            NUMERIC(12,6),
    benchmark_return_eur  NUMERIC(12,6),
    excess                NUMERIC(12,6),
    exit_kind             TEXT          NOT NULL,
    computed_at           TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT benchmark_outcome_kind_ck CHECK (kind IN ('SIGNAL', 'CANDIDATE')),
    CONSTRAINT benchmark_outcome_horizon_ck CHECK (horizon_days IN (20, 60)),
    CONSTRAINT benchmark_outcome_exit_kind_ck
        CHECK (exit_kind IN ('NORMAL', 'DELISTED_OFFER', 'DELISTED_LAST', 'NO_ENTRY')),
    CONSTRAINT benchmark_outcome_picked_ck CHECK ((kind = 'CANDIDATE') = (picked IS NOT NULL)),
    CONSTRAINT benchmark_outcome_uk UNIQUE (kind, agent, symbol, entry_ref_date, horizon_days)
);

CREATE INDEX idx_benchmark_outcome_event
    ON benchmark_outcome (kind, agent, symbol, event_start_date, horizon_days);

CREATE TABLE benchmark_symbol_no_data (
    symbol      TEXT  PRIMARY KEY,
    nights      INT   NOT NULL,
    last_night  DATE  NOT NULL
);
